export function isLocale(x: string): x is Locale {
  return (LANGUAGE_CODES as string[]).includes(x);
}

export function translate(locale: Locale, key: string, params?: Record<string, string>) {
  const dict = DICT[locale] ?? {};
  const en = DICT.en ?? {};
  const hasLocaleKey = Object.prototype.hasOwnProperty.call(dict, key);
  const hasEnKey = Object.prototype.hasOwnProperty.call(en, key);
  let out = dict[key] ?? en[key];

  if (!hasLocaleKey && hasEnKey) {
    if (__DEV__) {
      console.log("[i18n] Fallback to EN:", key, "locale:", locale);
    }
  }

  if (!hasLocaleKey && !hasEnKey) {
    if (__DEV__) {
      console.warn("[i18n] Missing key:", key, "locale:", locale);
    }
    out = key;
  }

  if (params) {
    for (const [k, v] of Object.entries(params)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}
